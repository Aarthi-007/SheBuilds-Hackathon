class MultimodalAnalyzer:
    """
    Refactored Multimodal Feature Extraction Engine for Klyros.
    
    Workflows:
    - Calculates SHA-256 asset hash before inference.
    - Checks AI Cache in FeatureStore. Returns cached features if hit.
    - Otherwise routes every feature request through FeatureRouter.
    - Writes all extracted features into `feature_store` MongoDB collection.
    """

    @classmethod
    async def extract_and_store_features_async(
        cls,
        brand_id: str,
        asset: Dict[str, Any],
        api_key: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """Extracts features from an asset and persists them into the Feature Store."""
        asset_id = str(asset.get("_id", asset.get("id", "")))
        asset_type = asset.get("asset_type", "image").lower()
        storage_path = asset.get("storage_path", "")
        key = api_key or settings.GROQ_API_KEY or settings.QWEN_API_KEY

        # Step 1: Generate SHA-256 hash for AI Cache
        asset_hash = FeatureStoreService.compute_asset_hash(storage_path, fallback_identifier=f"{brand_id}_{asset.get('filename', '')}")

        # Step 2: Check AI Cache
        cached_records = await FeatureStoreService.get_cached_features_async(asset_hash)
        if cached_records:
            logger.info("AI Cache Hit! Returning %d cached features for asset '%s'", len(cached_records), asset.get("filename"))
            return [
                {
                    "feature_name": r.feature_name,
                    "value": r.value,
                    "confidence": r.confidence,
                    "source_model": r.source_model,
                    "evidence": r.evidence
                }
                for r in cached_records
            ]

        # Step 3: Route feature extraction through FeatureRouter
        features_to_store = await FeatureRouter.extract_features_for_asset(asset, api_key=key)

        # Step 4: Persist extracted features into Feature Store
        await FeatureStoreService.store_features_async(
            brand_id=brand_id,
            asset_id=asset_id,
            asset_type=asset_type,
            asset_hash=asset_hash,
            features=features_to_store
        )

        # Step 5: Save Multimodal Embedding Fusion Memory to AIMemory database collection
        for feat in features_to_store:
            if feat.get("feature_name") == "embedding" and isinstance(feat.get("value"), list):
                try:
                    from app.models.identity import AIMemory
                    memory = AIMemory(
                        brand_id=brand_id,
                        entity_type="asset",
                        entity_id=asset_id,
                        content_text=f"Multimodal Embedding Fusion for {asset_type} asset '{asset.get('filename', '')}'",
                        embedding=feat["value"],
                        summary=f"Fused vector embedding generated by SentenceTransformer for {asset_type} asset",
                        embedding_model="SentenceTransformer / BGE-M3",
                        metadata={"asset_type": asset_type, "asset_id": asset_id}
                    )
                    await memory.insert()
                    logger.info("Multimodal Embedding Fusion stored in AIMemory for %s asset '%s'", asset_type, asset.get("filename"))
                except Exception as e:
                    logger.error("Error storing AIMemory embedding fusion for asset %s: %s", asset_id, e)

        return features_to_store

